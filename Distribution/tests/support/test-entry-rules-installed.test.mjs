import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import test from "node:test";
import { makeMe } from "./makeMe.mjs";
import { createPageObjectInstalledProject } from "./page-object-native-installed-fixture.mjs";

const root = fileURLToPath(new URL("../../../", import.meta.url));

test("a complete installed update retains standalone independent selection in every host layout", async (t) => {
  const directory = mkdtempSync(join(tmpdir(), "entry-installed-"));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  // Exact invalid flag values stay outside the valid domain builder.
  const nonboolean = {
    ...makeMe.anIntentLocation
      .at("nonboolean")
      .ofKind("javascript", ["**/*.spec.mjs"])
      .please(),
    makeMe: "true",
    pageObjects: 1,
  };
  const settings = makeMe.intentSettings
    .withLocations(
      ...[
        ["both", { makeMe: true, pageObjects: true }],
        ["pages", { makeMe: false, pageObjects: true }],
        ["data", { makeMe: true, pageObjects: false }],
        ["neither", {}],
      ].map(([path, rules]) =>
        makeMe.anIntentLocation
          .at(path)
          .ofKind("javascript", ["**/*.spec.mjs"])
          .withRules(rules)
          .please(),
      ),
      nonboolean,
      makeMe.anIntentLocation
        .at("both")
        .ofKind("javascript", ["**/*.spec.mjs"])
        .withRules({ makeMe: false, pageObjects: false })
        .please(),
      makeMe.anIntentLocation
        .at("custom")
        .withSources({ include: ["**/*.check"] })
        .withRules({ pageObjects: true })
        .please(),
    )
    .please();
  const configuration = `${JSON.stringify(settings, null, 2)}\n`;
  // Cursor is a distinct install entry context, sharing .agents with Codex.
  const fixture = await createPageObjectInstalledProject(
    join(directory, "project"),
    "cursor",
    {
      files: { ".planning/open-dough.json": configuration },
    },
  );
  const { project, source, sourceUrl, installLog, updateLog } = fixture;
  assert.doesNotMatch(
    readFileSync(installLog, "utf8"),
    /dough-(?:page-objects|makeme)/,
  );
  assert.match(readFileSync(updateLog, "utf8"), /updated.*0\.1\.2/);
  assert.equal(
    readFileSync(join(project, ".planning/open-dough.json"), "utf8"),
    configuration,
  );
  assert.equal(existsSync(join(project, "node_modules")), false);
  const declared = execFileSync(
    "bash",
    [
      "-c",
      'source "$1"; read_managed_files_declaration "$2"',
      "payload",
      join(
        source,
        "Distribution/src/install/open-dough-payload-declaration.sh",
      ),
      join(source, "install.sh"),
    ],
    { encoding: "utf8" },
  )
    .trim()
    .split("\n");
  const paths = [
    "both/new.spec.mjs",
    "pages/new.spec.mjs",
    "data/new.spec.mjs",
    "neither/new.spec.mjs",
    "nonboolean/new.spec.mjs",
    "custom/nested/new.check",
    "pages/helper.mjs",
    "custom/new.CHECK",
  ];
  const expected = {
    status: "resolved",
    sources: [
      { path: paths[0], makeMe: true, pageObjects: true },
      { path: paths[1], makeMe: false, pageObjects: true },
      { path: paths[2], makeMe: true, pageObjects: false },
      { path: paths[3], makeMe: false, pageObjects: false },
      { path: paths[4], makeMe: false, pageObjects: false },
      { path: paths[5], makeMe: false, pageObjects: true },
      { path: paths[6], makeMe: false, pageObjects: false },
      { path: paths[7], makeMe: false, pageObjects: false },
    ],
  };
  for (const layout of [".agents", ".claude"]) {
    const skills = join(project, layout, "skills");
    for (const path of declared)
      assert.deepEqual(
        readFileSync(join(skills, path)),
        readFileSync(join(source, "Distribution/src/skills", path)),
        path,
      );
    assert.equal(
      readFileSync(join(skills, "other-skill/SKILL.md"), "utf8"),
      "# Unrelated guidance\n",
    );
    assert.equal(
      readFileSync(join(skills, "dough-update/VERSION"), "utf8").trim(),
      "0.1.2",
    );
    assert.equal(
      readFileSync(join(skills, "dough-update/SOURCE"), "utf8").trim(),
      sourceUrl,
    );
    const scripts = join(skills, "dough-execute-plan/scripts");
    assert.match(
      readFileSync(join(scripts, "test-entry-rules-runtime.mjs"), "utf8"),
      /^\/\/ Generated by node scripts\/build-test-entry-rules\.mjs/,
    );
    assert.ok(
      readFileSync(
        join(scripts, "test-entry-rules-LICENSE.txt"),
        "utf8",
      ).trim(),
    );
    const run = () =>
      spawnSync(
        process.execPath,
        [
          join(scripts, "test-entry-rules.mjs"),
          "--project",
          project,
          ...paths.flatMap((path) => ["--source", path]),
        ],
        { cwd: directory, encoding: "utf8" },
      );
    const selected = run();
    assert.equal(selected.status, 0, selected.stderr);
    assert.deepEqual(JSON.parse(selected.stdout), expected);
    const config = join(project, ".planning/open-dough.json");
    writeFileSync(config, "{");
    const malformed = run();
    assert.equal(malformed.status, 1);
    assert.deepEqual(JSON.parse(malformed.stdout), {
      status: "unresolved",
      problem: "malformed",
      sources: [],
    });
    rmSync(config);
    const absent = run();
    assert.equal(absent.status, 0, absent.stderr);
    assert.deepEqual(JSON.parse(absent.stdout), {
      status: "resolved",
      configuration: "absent",
      sources: paths.map((path) => ({
        path,
        makeMe: false,
        pageObjects: false,
      })),
    });
    mkdirSync(config);
    const unreadable = run();
    assert.equal(unreadable.status, 1);
    assert.deepEqual(JSON.parse(unreadable.stdout), {
      status: "unresolved",
      problem: "unreadable",
      sources: [],
    });
    rmSync(config, { recursive: true });
    writeFileSync(config, configuration);
  }
  assert.equal(
    readFileSync(join(project, ".planning/open-dough.json"), "utf8"),
    configuration,
  );
  assert.equal(existsSync(join(project, "node_modules")), false);
  for (const skill of ["dough-page-objects", "dough-makeme"]) {
    for (const path of ["SKILL.md", "references/convention.md"]) {
      assert.deepEqual(
        readFileSync(join(project, ".agents/skills", skill, path)),
        readFileSync(join(root, "Distribution/src/skills", skill, path)),
      );
    }
  }
});
