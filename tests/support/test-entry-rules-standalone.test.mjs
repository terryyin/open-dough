import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import {
  cpSync,
  mkdtempSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import test from "node:test";
import { makeMe } from "./makeMe.mjs";

const root = fileURLToPath(new URL("../../", import.meta.url));
const runtime =
  "src/skills/dough-execute-plan/scripts/test-entry-rules-runtime.mjs";

test("the generated artifact retains regeneration and license provenance after minification", () => {
  const artifact = readFileSync(join(root, runtime), "utf8");
  const header = artifact.slice(0, 240);
  assert.match(
    header,
    /^\/\/ Generated by node scripts\/build-test-entry-rules\.mjs\. Do not edit\./,
  );
  const license = header.match(
    /^\/\/ .*licenses: (test-entry-rules-LICENSE\.txt)\.$/m,
  );
  assert.ok(
    license,
    "the artifact must name its bundled dependency license file",
  );
  assert.ok(
    readFileSync(join(root, dirname(runtime), license[1]), "utf8").trim(),
  );
});

test("the generated matcher corresponds to the maintained declaration and membership owners", () => {
  const before = readFileSync(join(root, runtime), "utf8");
  execFileSync(
    process.execPath,
    ["scripts/build-test-entry-rules.mjs", "--check"],
    { cwd: root },
  );
  assert.equal(readFileSync(join(root, runtime), "utf8"), before);
  assert.doesNotMatch(before, /\b(?:import\s*\(|from\s*["'])/);
});

test("the copied public command selects an intended new source without project dependencies", (t) => {
  const directory = mkdtempSync(join(tmpdir(), "test-entry-standalone-"));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  const project = join(directory, "project");
  const installed = join(directory, "installed");
  mkdirSync(join(project, ".planning"), { recursive: true });
  mkdirSync(installed);
  const settings = makeMe.intentSettings
    .withLocations(
      makeMe.anIntentLocation
        .at("browser")
        .ofKind("typescript", ["**/*.spec.ts"])
        .withRules({ makeMe: false, pageObjects: true })
        .please(),
    )
    .please();
  writeFileSync(
    join(project, ".planning/open-dough.json"),
    JSON.stringify(settings),
  );
  for (const name of [
    "test-entry-rules.mjs",
    "test-entry-rules-runtime.mjs",
    "ci-direct-entry.mjs",
  ]) {
    cpSync(
      join(root, "src/skills/dough-execute-plan/scripts", name),
      join(installed, name),
    );
  }
  const args = [
    join(installed, "test-entry-rules.mjs"),
    "--project",
    project,
    "--source",
    "browser/new.spec.ts",
  ];
  const run = () =>
    spawnSync(process.execPath, args, { cwd: directory, encoding: "utf8" });
  const selected = run();
  assert.equal(selected.status, 0, selected.stderr);
  assert.deepEqual(JSON.parse(selected.stdout), {
    status: "resolved",
    sources: [
      { path: "browser/new.spec.ts", makeMe: false, pageObjects: true },
    ],
  });
  writeFileSync(join(project, ".planning/open-dough.json"), "{");
  const malformed = run();
  assert.equal(malformed.status, 1);
  assert.deepEqual(JSON.parse(malformed.stdout), {
    status: "unresolved",
    problem: "malformed",
    sources: [],
  });
});
